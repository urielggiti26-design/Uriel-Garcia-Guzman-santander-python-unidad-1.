# 3. Estructuras de control - ejemplos del curso

# if
edad = 18

if edad >= 18:
    print("Eres mayor de edad.")

# if - else
edad = 15

if edad >= 18:
    print("Eres mayor de edad.")
else:
    print("eres menor de edad.")

# if - elif - else
calificacion = 85

if calificacion >= 90:
    print("Excelente")
elif calificacion >= 80:
    print("Muy bueno")
elif calificacion >= 70:
    print("Bueno")
else:
    print("Necesita mejorar")
